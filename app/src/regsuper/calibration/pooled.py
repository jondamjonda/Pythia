"""Pooled-relevance helpers for the calibration labelling workflow.

For each seed query, the top-N reranked retrieval candidates are materialised into
`retrieval_eval` rows sharing one `query_group_id`. The lawyer judges each as `relevant`,
`partial` or `not_relevant`, and a search helper lets them add provisions that should have been
retrieved. After materialisation, the rows for one query_group_id are:

  - the anchor row (notes='seed · generated by ...', rank_position=NULL);
  - up to N rows from system retrieval (rank_position=1..N, with rerank_score);
  - zero or more rows added by the lawyer (added_by_lawyer=TRUE, rank_position=NULL).
"""

from __future__ import annotations

import datetime as dt
from dataclasses import dataclass
from typing import Any
from uuid import UUID

from sqlalchemy import select
from sqlalchemy import text as sql_text

from regsuper.retrieval import RetrievalFilters, retrieve
from regsuper.storage.database import session_scope
from regsuper.storage.models import RetrievalEval


@dataclass
class EvalQueryGroup:
    """One query's labelling queue, as iterated by the UI."""

    group_id: UUID
    query: str
    expected_provision_id: UUID | None
    anchor_row_id: UUID
    rows: list[RetrievalEval]
    is_materialised: bool  # True when at least one retrieval-candidate row exists

    @property
    def n_labeled(self) -> int:
        return sum(1 for r in self.rows if r.label_kind or r.label)

    @property
    def n_total(self) -> int:
        return len(self.rows)


async def list_query_groups(
    *,
    only_unfinished: bool = True,
    limit: int = 200,
) -> list[EvalQueryGroup]:
    """List query groups, oldest first.

    A group is finished once it is materialised and every non-anchor row has a label;
    `only_unfinished` skips finished groups.
    """
    async with session_scope() as session:
        rows = (
            (
                await session.execute(
                    select(RetrievalEval)
                    .where(RetrievalEval.query_group_id.is_not(None))
                    .order_by(RetrievalEval.created_at, RetrievalEval.rank_position.nulls_first())
                )
            )
            .scalars()
            .all()
        )

    groups: dict[UUID, list[RetrievalEval]] = {}
    for r in rows:
        groups.setdefault(r.query_group_id, []).append(r)

    out: list[EvalQueryGroup] = []
    for gid, gr in groups.items():
        # The anchor is the row whose id equals query_group_id (created first).
        anchor = next((r for r in gr if r.id == gid), gr[0])
        materialised = any(r.rank_position is not None for r in gr)
        all_labeled = all((r.label_kind or r.label) for r in gr if r.id != gid)
        if only_unfinished and materialised and all_labeled:
            continue
        out.append(
            EvalQueryGroup(
                group_id=gid,
                query=anchor.query,
                expected_provision_id=anchor.expected_provision_id,
                anchor_row_id=anchor.id,
                rows=gr,
                is_materialised=materialised,
            )
        )
        if len(out) >= limit:
            break
    return out


async def materialise_top_n(
    *,
    group_id: UUID,
    top_n: int = 10,
) -> int:
    """Run the retrieval orchestrator for the group's query and persist its top-N candidates.

    Writes one `retrieval_eval` row per candidate. Idempotent: candidates that already have a
    row in this group are left untouched. Returns the number of new rows created.
    """
    async with session_scope() as session:
        anchor = (
            await session.execute(select(RetrievalEval).where(RetrievalEval.id == group_id))
        ).scalar_one_or_none()
    if anchor is None:
        raise LookupError(f"query group {group_id} not found")

    # Run the pipeline for the anchor query.
    result = await retrieve(
        anchor.query,
        jurisdiction="EU+CZ",
        sector="fin_services",
        filters=RetrievalFilters(jurisdictions=["EU", "CZ"], active_only=True),
        top_n_rerank=top_n,
        expand_top_n=0,
        use_cache=True,
    )

    # Existing rows for this group, indexed by retrieved_provision_id.
    async with session_scope() as session:
        existing = (
            (
                await session.execute(
                    select(RetrievalEval).where(
                        RetrievalEval.query_group_id == group_id,
                        RetrievalEval.id != group_id,  # exclude the anchor
                    )
                )
            )
            .scalars()
            .all()
        )
    seen = {r.retrieved_provision_id for r in existing}

    rows_to_add = []
    for rank, hit in enumerate(result.candidates, start=1):
        if hit.provision_id in seen:
            continue
        rows_to_add.append(
            {
                "query": anchor.query,
                "expected_provision_id": anchor.expected_provision_id,
                "retrieved_provision_id": hit.provision_id,
                "retrieval_score": float(hit.rrf_score or 0.0),
                "rerank_score": hit.rerank_score,
                "label": None,
                "labeled_by": None,
                "labeled_at": None,
                "notes": "auto-materialised top-N",
                "query_group_id": group_id,
                "rank_position": rank,
                "added_by_lawyer": False,
                "label_kind": None,
            }
        )

    if not rows_to_add:
        return 0

    async with session_scope() as session:
        for data in rows_to_add:
            session.add(RetrievalEval(**data))
        await session.flush()
    return len(rows_to_add)


# ---------------------------------------------------------------------------
# Lawyer additions: search the corpus and append a provision the lawyer says is also
# relevant for this query.
# ---------------------------------------------------------------------------
@dataclass
class ProvisionSearchHit:
    provision_id: UUID
    external_id: str | None
    label: str | None
    title: str | None
    snippet: str


async def search_provisions(query: str, *, limit: int = 12) -> list[ProvisionSearchHit]:
    """Cheap text-based search the lawyer uses to find provisions to add.

    Tries, in order: (1) an external_id plus label match such as "240/2013 § 303" (both by
    substring); (2) ILIKE on label or external_id; (3) plain full-text search on
    provision.text. The mix is deliberately forgiving: lawyers type short strings and expect
    it to just work.
    """
    if not query or not query.strip():
        return []
    q = query.strip()

    # Pattern 1: "<external_id> <label>", e.g. "240/2013 § 303" or "32011L0061 Article 31".
    parts = q.split(maxsplit=1)
    if len(parts) == 2:
        ext, lab = parts
        async with session_scope() as session:
            rows = (
                await session.execute(
                    sql_text(
                        """
                SELECT p.id, sd.external_id, p.label, sd.title, left(p.text, 220)
                  FROM provision p
                  JOIN source_document sd ON sd.id = p.source_document_id
                 WHERE sd.external_id ILIKE :ext
                   AND p.label ILIKE :lab
                 LIMIT :lim
                """
                    ),
                    {"ext": f"%{ext}%", "lab": f"%{lab}%", "lim": limit},
                )
            ).all()
        if rows:
            return [_to_hit(r) for r in rows]

    # Pattern 2: ILIKE on label or external_id.
    async with session_scope() as session:
        rows = (
            await session.execute(
                sql_text(
                    """
            SELECT p.id, sd.external_id, p.label, sd.title, left(p.text, 220)
              FROM provision p
              JOIN source_document sd ON sd.id = p.source_document_id
             WHERE (sd.external_id ILIKE :q OR p.label ILIKE :q)
             LIMIT :lim
            """
                ),
                {"q": f"%{q}%", "lim": limit},
            )
        ).all()
    if rows:
        return [_to_hit(r) for r in rows]

    # Pattern 3: full-text search on the provision body.
    async with session_scope() as session:
        rows = (
            await session.execute(
                sql_text(
                    """
            SELECT p.id, sd.external_id, p.label, sd.title, left(p.text, 220)
              FROM provision p
              JOIN source_document sd ON sd.id = p.source_document_id
             WHERE p.tsv @@ websearch_to_tsquery('simple', :q)
             ORDER BY ts_rank_cd(p.tsv, websearch_to_tsquery('simple', :q)) DESC
             LIMIT :lim
            """
                ),
                {"q": q, "lim": limit},
            )
        ).all()
    return [_to_hit(r) for r in rows]


def _to_hit(row: Any) -> ProvisionSearchHit:
    return ProvisionSearchHit(
        provision_id=row[0],
        external_id=row[1],
        label=row[2],
        title=row[3],
        snippet=(row[4] or ""),
    )


async def append_lawyer_provision(
    *,
    group_id: UUID,
    provision_id: UUID,
    labeler: str,
    label_kind: str = "relevant",
    notes: str = "",
) -> UUID:
    """Append a lawyer-chosen provision to the query group with its label attached.

    The label defaults to 'relevant', since the lawyer adds a provision because it belongs. If
    the provision is already in the group, that row is relabelled instead and its id returned.
    """
    async with session_scope() as session:
        anchor = (
            await session.execute(select(RetrievalEval).where(RetrievalEval.id == group_id))
        ).scalar_one()
        # Guard against duplicate adds.
        dup = (
            await session.execute(
                select(RetrievalEval).where(
                    RetrievalEval.query_group_id == group_id,
                    RetrievalEval.retrieved_provision_id == provision_id,
                    RetrievalEval.id != group_id,
                )
            )
        ).scalar_one_or_none()
        if dup is not None:
            dup.label_kind = label_kind
            dup.label = "relevant" if label_kind in ("relevant", "partial") else "not_relevant"
            dup.labeled_by = labeler
            dup.labeled_at = dt.datetime.now(dt.UTC)
            dup.added_by_lawyer = True
            dup.notes = (notes or dup.notes or "")[:1000]
            return dup.id

        row = RetrievalEval(
            query=anchor.query,
            expected_provision_id=anchor.expected_provision_id,
            retrieved_provision_id=provision_id,
            retrieval_score=0.0,
            rerank_score=None,
            label="relevant" if label_kind in ("relevant", "partial") else "not_relevant",
            label_kind=label_kind,
            labeled_by=labeler,
            labeled_at=dt.datetime.now(dt.UTC),
            notes=notes or "added by lawyer (out-of-retrieval pool)",
            query_group_id=group_id,
            rank_position=None,
            added_by_lawyer=True,
        )
        session.add(row)
        await session.flush()
        return row.id


async def label_row(
    *,
    row_id: UUID,
    label_kind: str,
    labeler: str,
) -> None:
    """Mark a single retrieval_eval row with the lawyer's verdict."""
    bin_label = "relevant" if label_kind in ("relevant", "partial") else "not_relevant"
    async with session_scope() as session:
        row = (
            await session.execute(select(RetrievalEval).where(RetrievalEval.id == row_id))
        ).scalar_one()
        row.label = bin_label
        row.label_kind = label_kind
        row.labeled_by = labeler
        row.labeled_at = dt.datetime.now(dt.UTC)


async def reject_group(group_id: UUID, *, labeler: str) -> None:
    """Mark every unlabelled row in the group as not_relevant.

    Used when the lawyer judges the query itself to be nonsense or unusable.
    """
    async with session_scope() as session:
        rows = (
            (
                await session.execute(
                    select(RetrievalEval).where(RetrievalEval.query_group_id == group_id)
                )
            )
            .scalars()
            .all()
        )
        for r in rows:
            if r.label_kind is None:
                r.label_kind = "not_relevant"
                r.label = "not_relevant"
                r.labeled_by = labeler
                r.labeled_at = dt.datetime.now(dt.UTC)
                r.notes = (r.notes or "") + " · query rejected by lawyer"
